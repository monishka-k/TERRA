/** Projection constants centering on Jabalpur/Nagpur (Subcontinent Geographic Centroid) */
export const PROJECTION_CENTER = {
  lng: 82.5,
  lat: 22.5,
  scale: 2.2,
};

/**
 * Projects a [longitude, latitude] coordinate into Three.js 3D world space (X, Y).
 * Applies latitude cosine scaling to prevent east-west distortion.
 */
export function latLngTo3D(lng: number, lat: number, customScale?: number): { x: number; y: number } {
  const scale = customScale ?? PROJECTION_CENTER.scale;
  const radLat = (PROJECTION_CENTER.lat * Math.PI) / 180;
  const cosLat = Math.cos(radLat);
  const x = (lng - PROJECTION_CENTER.lng) * cosLat * scale;
  const y = (lat - PROJECTION_CENTER.lat) * scale;
  return { x, y };
}

/**
 * Inverse of `latLngTo3D` — maps a world-space (x, y) back to [longitude, latitude].
 * Used to resolve a pointer ray hit on the map plane directly to an H3 index,
 * which avoids raycasting every hexagon in the grid.
 */
export function world3DToLatLng(
  x: number,
  y: number,
  customScale?: number,
): { lng: number; lat: number } {
  const scale = customScale ?? PROJECTION_CENTER.scale;
  const radLat = (PROJECTION_CENTER.lat * Math.PI) / 180;
  const cosLat = Math.cos(radLat);
  const lng = x / (cosLat * scale) + PROJECTION_CENTER.lng;
  const lat = y / scale + PROJECTION_CENTER.lat;
  return { lng, lat };
}

